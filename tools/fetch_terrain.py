"""Fetch real elevation data for St. Anton am Arlberg and bake it into data/terrain.js.

Source: Mapzen/AWS "Terrain Tiles" (terrarium encoding), public dataset on AWS Open Data.
        Over Austria the underlying DEM is the 10 m data.gv.at model.
Usage:  python -I tools/fetch_terrain.py <tile_cache_dir> <output_js>
"""
import base64, io, json, math, os, sys, urllib.request
import numpy as np
from PIL import Image

# Bounding box around St. Anton: Valluga/Galzig/Kapall (north), Rendl (south), St. Christoph (west)
LON0, LON1 = 10.170, 10.320
LAT0, LAT1 = 47.080, 47.180
ZOOM = 12
GRID_W, GRID_H = 384, 376          # ~30 m cells

cache, out = sys.argv[1], sys.argv[2]
os.makedirs(cache, exist_ok=True)


def merc(lon, lat, z):
    n = 2 ** z
    x = (lon + 180.0) / 360.0 * n
    r = math.radians(lat)
    y = (1.0 - math.log(math.tan(r) + 1.0 / math.cos(r)) / math.pi) / 2.0 * n
    return x, y


x0, y1 = merc(LON0, LAT0, ZOOM)
x1, y0 = merc(LON1, LAT1, ZOOM)
tx0, tx1 = int(x0), int(x1)
ty0, ty1 = int(y0), int(y1)

mosaic = np.zeros(((ty1 - ty0 + 1) * 256, (tx1 - tx0 + 1) * 256), dtype=np.float64)
for ty in range(ty0, ty1 + 1):
    for tx in range(tx0, tx1 + 1):
        path = os.path.join(cache, f"{ZOOM}_{tx}_{ty}.png")
        if not os.path.exists(path):
            url = f"https://s3.amazonaws.com/elevation-tiles-prod/terrarium/{ZOOM}/{tx}/{ty}.png"
            print("fetch", url)
            req = urllib.request.Request(url, headers={"User-Agent": "terrain-fetch/1.0"})
            with urllib.request.urlopen(req, timeout=60) as r, open(path, "wb") as f:
                f.write(r.read())
        img = np.asarray(Image.open(path).convert("RGB"), dtype=np.float64)
        h = img[:, :, 0] * 256.0 + img[:, :, 1] + img[:, :, 2] / 256.0 - 32768.0
        mosaic[(ty - ty0) * 256:(ty - ty0 + 1) * 256, (tx - tx0) * 256:(tx - tx0 + 1) * 256] = h

grid = np.zeros((GRID_H, GRID_W), dtype=np.float64)
for j in range(GRID_H):
    lat = LAT1 + (LAT0 - LAT1) * j / (GRID_H - 1)      # row 0 = north
    for i in range(GRID_W):
        lon = LON0 + (LON1 - LON0) * i / (GRID_W - 1)
        mx, my = merc(lon, lat, ZOOM)
        px = (mx - tx0) * 256.0 - 0.5
        py = (my - ty0) * 256.0 - 0.5
        ix, iy = int(px), int(py)
        fx, fy = px - ix, py - iy
        a = mosaic[iy, ix]; b = mosaic[iy, ix + 1]
        c = mosaic[iy + 1, ix]; d = mosaic[iy + 1, ix + 1]
        grid[j, i] = (a * (1 - fx) + b * fx) * (1 - fy) + (c * (1 - fx) + d * fx) * fy

lat_c = (LAT0 + LAT1) / 2
width_m = (LON1 - LON0) * 111320.0 * math.cos(math.radians(lat_c))
height_m = (LAT1 - LAT0) * 111194.0

u16 = np.clip(np.round(grid * 10.0), 0, 65535).astype("<u2")
meta = {
    "w": GRID_W, "h": GRID_H,
    "lon0": LON0, "lon1": LON1, "lat0": LAT0, "lat1": LAT1,
    "widthM": round(width_m, 1), "heightM": round(height_m, 1),
    "minH": round(float(grid.min()), 1), "maxH": round(float(grid.max()), 1),
    "source": "AWS Terrain Tiles (terrarium), z12 - data.gv.at DEM",
}
with open(out, "w", encoding="utf-8") as f:
    f.write("// Real elevation data: St. Anton am Arlberg. Generated by tools/fetch_terrain.py\n")
    f.write("window.TERRAIN_DATA = " + json.dumps(meta) + ";\n")
    f.write('window.TERRAIN_DATA.b64 = "' + base64.b64encode(u16.tobytes()).decode("ascii") + '";\n')

print(json.dumps(meta, indent=1))


def at(lat, lon):
    i = (lon - LON0) / (LON1 - LON0) * (GRID_W - 1)
    j = (LAT1 - lat) / (LAT1 - LAT0) * (GRID_H - 1)
    return i, j


# sanity check against known landmarks (local max within ~600 m for summits)
for name, lat, lon, summit in [("Valluga", 47.1575, 10.2131, 1), ("St. Anton", 47.1287, 10.2670, 0),
                               ("Galzig", 47.1308, 10.2275, 1), ("Kapall", 47.1497, 10.2600, 0),
                               ("Gampen", 47.1397, 10.2625, 0), ("St. Christoph", 47.1283, 10.2135, 0),
                               ("Rendl", 47.1090, 10.2640, 0), ("Schindler Spitze", 47.1475, 10.2020, 1),
                               ("Nasserein", 47.1345, 10.2820, 0), ("Riffelscharte", 47.0930, 10.2560, 0)]:
    i, j = at(lat, lon)
    i, j = int(round(i)), int(round(j))
    if summit:
        r = 20
        sub = grid[max(0, j - r):j + r + 1, max(0, i - r):i + r + 1]
        jj, ii = np.unravel_index(np.argmax(sub), sub.shape)
        j2, i2 = max(0, j - r) + jj, max(0, i - r) + ii
        lon2 = LON0 + (LON1 - LON0) * i2 / (GRID_W - 1)
        lat2 = LAT1 + (LAT0 - LAT1) * j2 / (GRID_H - 1)
        print(f"{name:18s} peak {grid[j2, i2]:.0f} m at {lat2:.4f},{lon2:.4f}")
    else:
        print(f"{name:18s} {grid[j, i]:.0f} m")
